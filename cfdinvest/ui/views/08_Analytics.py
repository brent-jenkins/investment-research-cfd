"""Analytics — parameter sweeps, walk-forward and Monte Carlo.

Everything on this page is produced by ``cfdinvest-analytics``, because each
one re-runs the pipeline many times and none of it can honestly be computed
inside a web request. The page reads what that tool wrote and nothing else.
"""

from __future__ import annotations

import sys
from pathlib import Path

_ROOT = str(Path(__file__).resolve().parents[3])
if _ROOT not in sys.path:
    sys.path.insert(0, _ROOT)

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
import streamlit as st  # noqa: E402

from cfdinvest.ui import components, sources  # noqa: E402

data = components.page_setup(
    st,
    "Analytics",
    icon="🔬",
    subtitle="Parameter sweeps, walk-forward evaluation and trade resampling. "
    "Generated by the analytics tool, read here.",
)
config = data["config"]

stored = sources.load_stored_analytics(config, (data["summary"].value or {}).get("run_id"))

if components.render_absent(st, stored, "Stored analytics"):
    st.subheader("How to produce them")
    st.code(
        "cfdinvest-analytics run-once     --tickers SPY,GLD\n"
        "cfdinvest-analytics sweep        --grid '{\"execution.max_leverage\": [2, 5]}'\n"
        "cfdinvest-analytics walkforward  --train 365D --test 90D\n"
        "cfdinvest-analytics montecarlo   --paths 2000",
        language="bash",
    )
    components.render_note(
        st,
        "Each command reads the lake and writes into `<data root>/analytics/`. "
        "None of them trades, and none of them changes a recorded run.",
    )
    st.stop()

payload = stored.value
if payload.get("is_fallback"):
    components.render_note(
        st,
        f"The latest pipeline run has no analytics, so this shows run "
        f"`{payload['run_id']}` — the most recent that does. Pass "
        "`--run-id` to the analytics tool to pair them up.",
    )

st.caption(
    f"Analytics run `{payload['run_id']}` · "
    f"{len(payload['available_runs'])} on disk"
)

warnings = payload.get("warnings") or []
if warnings:
    for warning in warnings:
        st.warning(warning)

tabs = st.tabs(["Parameter sweep", "Walk-forward", "Monte Carlo", "Scored run"])

# --------------------------------------------------------------------------- #
# Sweep
# --------------------------------------------------------------------------- #
with tabs[0]:
    sweep = payload.get("sweep")
    if sweep is None or sweep.empty:
        components.render_note(
            st, "No parameter sweep was written for this run."
        )
    else:
        components.render_note(
            st,
            "**A sweep is a multiple-comparisons machine.** Run enough "
            "combinations and one looks excellent by luck alone, so the best "
            "row here is an upper bound on what the strategy does rather than "
            "an estimate of it. Walk-forward answers the other question.",
        )
        components.render_frame(st, sweep, height=420)

        numeric = sweep.select_dtypes("number")
        if "sharpe_ratio" in numeric.columns and len(numeric) > 1:
            st.caption("Sharpe ratio by combination")
            chart = sweep.set_index(
                sweep.columns[0] if sweep.index.name is None else sweep.index
            )["sharpe_ratio"] if "sharpe_ratio" in sweep.columns else None
            if chart is not None:
                st.bar_chart(chart, height=260)

# --------------------------------------------------------------------------- #
# Walk-forward
# --------------------------------------------------------------------------- #
with tabs[1]:
    windows = payload.get("walkforward")
    summary = payload.get("walkforward_summary") or {}

    if windows is None or windows.empty:
        components.render_note(
            st, "No walk-forward evaluation was written for this run."
        )
    else:
        cells = st.columns(3)
        cells[0].metric("Windows", summary.get("windows", len(windows)))
        cells[1].metric("Failed", summary.get("failed", 0))

        stability = pd.DataFrame(summary.get("stability") or [])
        if not stability.empty and "mean_drift" in stability.columns:
            sharpe = stability[stability.iloc[:, 0] == "sharpe_ratio"]
            if not sharpe.empty:
                cells[2].metric(
                    "Sharpe drift",
                    components.number(sharpe["mean_drift"].iloc[0], 3),
                    help="Test minus train. Negative is expected; the size is "
                    "the finding.",
                )

        components.render_note(
            st,
            "**The column to read is `mean_drift`.** Consistently negative "
            "means the in-sample result did not survive. A large `std_test` "
            "means it survives sometimes, which is worse than a small "
            "consistent decay because it cannot be planned around.",
        )
        components.render_frame(st, stability, height=280)

        st.subheader("Every window")
        components.render_frame(st, windows, height=380)

        columns = [c for c in ("test_sharpe_ratio", "train_sharpe_ratio")
                   if c in windows.columns]
        if columns:
            st.caption("Sharpe ratio, in sample against out of sample")
            st.line_chart(windows[columns], height=260)

# --------------------------------------------------------------------------- #
# Monte Carlo
# --------------------------------------------------------------------------- #
with tabs[2]:
    carlo = payload.get("montecarlo")
    paths = payload.get("montecarlo_paths")

    if not carlo:
        components.render_note(
            st, "No Monte Carlo resampling was written for this run."
        )
    else:
        cells = st.columns(4)
        cells[0].metric("Paths", carlo.get("paths", 0))
        cells[1].metric(
            "Median return", components.percent(carlo.get("median_return"))
        )
        cells[2].metric(
            "5th percentile",
            components.percent(carlo.get("tail_loss")),
            help="A twentieth of paths did worse than this. The number to "
            "size against.",
        )
        cells[3].metric(
            "Chance of a loss",
            components.percent(carlo.get("probability_of_loss")),
        )

        components.render_note(
            st,
            "Trades are drawn independently, which preserves the distribution "
            "of individual outcomes and **destroys the relationships between "
            "them** — the losing streak that came from one bad fortnight, the "
            "volatility clustering that fired three stops in a week. Real "
            "losing runs are longer than independent draws produce, so the "
            "drawdown figures here are a floor, not an estimate.",
        )

        drawdowns = st.columns(2)
        drawdowns[0].metric(
            "Median drawdown", components.percent(carlo.get("median_drawdown"))
        )
        drawdowns[1].metric(
            "Worst drawdown", components.percent(carlo.get("worst_drawdown"))
        )

        distributions = pd.DataFrame(carlo.get("distributions") or {}).T
        if not distributions.empty:
            st.subheader("Distribution by metric")
            components.render_frame(st, distributions, height=320)

        if paths is not None and not paths.empty:
            for column, label in (
                ("total_return", "Final return across paths"),
                ("max_drawdown_fraction", "Maximum drawdown across paths"),
            ):
                if column in paths.columns:
                    st.caption(label)
                    values = pd.to_numeric(paths[column], errors="coerce").dropna()
                    counts, edges = np.histogram(values, bins=40)
                    st.bar_chart(
                        pd.DataFrame(
                            {label: counts},
                            index=np.round((edges[:-1] + edges[1:]) / 2, 4),
                        ),
                        height=240,
                    )

# --------------------------------------------------------------------------- #
# The scored run
# --------------------------------------------------------------------------- #
with tabs[3]:
    metrics = payload.get("metrics")
    if not metrics:
        components.render_note(
            st,
            "No scored run was written. `cfdinvest-analytics run-once` "
            "produces it.",
        )
    else:
        st.caption(
            f"Universe: {', '.join(metrics.get('universe') or []) or components.DASH} · "
            f"{components.plural(metrics.get('bars', 0), 'bar')} · "
            f"{components.plural(metrics.get('trade_count', 0), 'trade')}"
        )
        flat = metrics.get("metrics") or {}
        rows = {
            key: value
            for key, value in flat.items()
            if isinstance(value, (int, float, str, bool)) or value is None
        }
        components.render_frame(
            st,
            pd.DataFrame({"measure": list(rows), "value": list(rows.values())}),
            height=360,
        )

        snapshot = metrics.get("config_snapshot") or {}
        if snapshot:
            with st.expander("The configuration that produced it", expanded=False):
                components.render_frame(
                    st,
                    pd.DataFrame(
                        {"setting": list(snapshot), "value": list(snapshot.values())}
                    ),
                    height=420,
                )
